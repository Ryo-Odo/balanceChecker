BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(8) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(10) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS foods (
    id INTEGER PRIMARY KEY,
    food_group INTEGER NOT NULL,
    food_name TEXT NOT NULL,
    energy DOUBLE PRECISION NOT NULL DEFAULT 0,
    moisture DOUBLE PRECISION NOT NULL DEFAULT 0,
    protein DOUBLE PRECISION NOT NULL DEFAULT 0,
    lipid DOUBLE PRECISION NOT NULL DEFAULT 0,
    food_fiber DOUBLE PRECISION NOT NULL DEFAULT 0,
    carbohydrate DOUBLE PRECISION NOT NULL DEFAULT 0,
    natrium DOUBLE PRECISION NOT NULL DEFAULT 0,
    potassium DOUBLE PRECISION NOT NULL DEFAULT 0,
    calcium DOUBLE PRECISION NOT NULL DEFAULT 0,
    magnesium DOUBLE PRECISION NOT NULL DEFAULT 0,
    phosphorus DOUBLE PRECISION NOT NULL DEFAULT 0,
    iron DOUBLE PRECISION NOT NULL DEFAULT 0,
    zinc DOUBLE PRECISION NOT NULL DEFAULT 0,
    copper DOUBLE PRECISION NOT NULL DEFAULT 0,
    manganese DOUBLE PRECISION NOT NULL DEFAULT 0,
    iodine DOUBLE PRECISION NOT NULL DEFAULT 0,
    selenium DOUBLE PRECISION NOT NULL DEFAULT 0,
    chrome DOUBLE PRECISION NOT NULL DEFAULT 0,
    molybdenum DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_a DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_d DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_e DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_k DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_b1 DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_b2 DOUBLE PRECISION NOT NULL DEFAULT 0,
    niacin DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_b6 DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_b12 DOUBLE PRECISION NOT NULL DEFAULT 0,
    folic_acid DOUBLE PRECISION NOT NULL DEFAULT 0,
    pantothenic_acid DOUBLE PRECISION NOT NULL DEFAULT 0,
    biotin DOUBLE PRECISION NOT NULL DEFAULT 0,
    vitamin_c DOUBLE PRECISION NOT NULL DEFAULT 0,
    sodium_content DOUBLE PRECISION NOT NULL DEFAULT 0,
    other TEXT
);

CREATE TABLE IF NOT EXISTS food_name (
    id INTEGER PRIMARY KEY,
    food_group INTEGER NOT NULL,
    food_name TEXT NOT NULL,
    other TEXT
);

CREATE INDEX IF NOT EXISTS idx_food_name_name ON food_name (food_name);

COMMIT;
